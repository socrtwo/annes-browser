/**
 * Census operations. Library functions, so tests can drive them with an in-memory fetcher.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse, stringify } from 'yaml';
import { extract } from './extractors.ts';
import { type Fetcher, getSource, resolveRef, sha256 } from './fetch.ts';
import type { CensusFile, SourceSpec } from './types.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const CENSUS_DIR = join(root, 'catalog', 'census');
export const SOURCES_PATH = join(CENSUS_DIR, 'sources.yaml');

export const loadSources = (): SourceSpec[] => parse(readFileSync(SOURCES_PATH, 'utf8')) as SourceSpec[];

export function loadCensus(id: string): CensusFile {
  return parse(readFileSync(join(CENSUS_DIR, `${id}.yaml`), 'utf8')) as CensusFile;
}

/** Resolve each source's ref to a commit SHA and write it back to sources.yaml. Existing pins are kept. */
export function pinSources(resolve: (repo: string, ref: string) => string = resolveRef): number {
  const specs = loadSources();
  let changed = 0;
  // Same repo and ref resolve once.
  const memo = new Map<string, string>();
  for (const s of specs) {
    if (s.commit) continue;
    const k = `${s.repo}@${s.ref}`;
    if (!memo.has(k)) memo.set(k, resolve(s.repo, s.ref));
    s.commit = memo.get(k)!;
    changed++;
  }
  if (changed) {
    // Rewrite compactly: one flow-style line for short entries is not preserved by the serializer, so write block style.
    const header = readFileSync(SOURCES_PATH, 'utf8').split('\n').filter((l) => l.startsWith('#')).join('\n');
    writeFileSync(SOURCES_PATH, `${header.split('\n\n')[0]}\n\n${stringify(specs, { lineWidth: 0 })}`);
  }
  return changed;
}

export async function readFiles(spec: SourceSpec, fetcher?: Fetcher): Promise<Record<string, string>> {
  if (!spec.commit) throw new Error(`${spec.id}: not pinned; run "census pin"`);
  const out: Record<string, string> = {};
  for (const f of spec.files) out[f.path] = await getSource({ repo: spec.repo, commit: spec.commit, path: f.path }, fetcher);
  return out;
}

export async function buildCensus(spec: SourceSpec, today: string, fetcher?: Fetcher): Promise<CensusFile> {
  const files = await readFiles(spec, fetcher);
  return {
    version: 1,
    id: spec.id,
    browser: spec.browser,
    browser_version: spec.version,
    released: spec.released,
    platform: spec.platform,
    source: {
      repo: spec.repo,
      ref: spec.ref,
      commit: spec.commit!,
      extractor: spec.extractor,
      files: spec.files.map((f) => ({ path: f.path, sha256: sha256(files[f.path]!), lines: files[f.path]!.split('\n').length, role: f.role })),
      retrieved: today,
    },
    items: extract(spec, files),
  };
}

export function writeCensus(c: CensusFile): void {
  const text = stringify(c, { lineWidth: 0 });
  writeFileSync(join(CENSUS_DIR, `${c.id}.yaml`), `# Generated by \`npm run census -- extract\` from ${c.source.repo}@${c.source.commit.slice(0, 12)}. Do not edit by hand.\n${text}`);
}

export interface VerifyProblem { id: string; message: string }

/**
 * Re-read each census file's sources and check that they still match: same hash,
 * and every item's evidence text on the line it cites.
 */
export async function verifyCensus(c: CensusFile, fetcher?: Fetcher): Promise<VerifyProblem[]> {
  const problems: VerifyProblem[] = [];
  const fail = (message: string) => problems.push({ id: c.id, message });
  const texts: Record<string, string[]> = {};
  for (const f of c.source.files) {
    const text = await getSource({ repo: c.source.repo, commit: c.source.commit, path: f.path }, fetcher);
    if (sha256(text) !== f.sha256) fail(`${f.path}: content hash differs from the one recorded`);
    texts[f.path] = text.split(/\r?\n/);
  }
  const first = c.source.files[0]!.path;
  const seen = new Set<string>();
  for (const it of c.items) {
    if (seen.has(it.key)) fail(`duplicate key ${it.key}`);
    seen.add(it.key);
    const lines = texts[it.file ?? first];
    if (!lines) { fail(`${it.key}: cites unknown file ${it.file}`); continue; }
    const text = lines[it.line - 1];
    if (text === undefined) { fail(`${it.key}: line ${it.line} does not exist`); continue; }
    const want = it.evidence.endsWith('…') ? it.evidence.slice(0, -1) : it.evidence;
    if (!text.trim().startsWith(want) && !text.includes(want)) fail(`${it.key}: line ${it.line} does not contain the recorded evidence`);
  }
  return problems;
}
