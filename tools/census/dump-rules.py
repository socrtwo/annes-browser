def clean(s):
    s = re.sub(r'(\\t|\t).*$', '', s).replace('&', '')
    return re.sub(r'\.\.\.$|…$', '', s).strip().lower()

rows = [r for r in csv.DictReader(open('docs/census-unlinked.tsv'), delimiter='\t') if re.search(ANY, r['source'])]
existing = {(o['source'], str(o['key'])) for o in yaml.safe_load(open('catalog/census/overrides.yaml'))}
out, used, seen = [], set(), set()
for r in rows:
    k = (r['source'], r['key'])
    if k in existing or k in seen:
        continue
    lab, menu = clean(r['label_or_note']), r['menu_or_group']
    for i, (src, lp, mp, cmd) in enumerate(R):
        if re.search(src, r['source']) and re.search(lp, lab) and (mp is None or re.search(mp, menu)):
            seen.add(k); used.add(i)
            key = r['key'] if re.fullmatch(r'[A-Za-z_][\w]*', r['key']) else f'"{r["key"]}"'
            if isinstance(cmd, tuple):
                why = cmd[1].replace('"', "'")
                out.append(f'- {{ source: {r["source"]}, key: {key}, command: none, why: "{why}" }}')
            else:
                out.append(f'- {{ source: {r["source"]}, key: {key}, command: {cmd} }}')
            break
print('# ---- generated from the rule table for dumped menus (one line per item; each rule was checked against the item\'s menu and status text) ----')
print('\n'.join(out))
unused = [R[i][1] for i in range(len(R)) if i not in used]
print(f'{len(out)} overrides; unused rules: {unused}', file=sys.stderr)
