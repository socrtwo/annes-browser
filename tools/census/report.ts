/** Generate docs/CENSUS.md and docs/census-unlinked.tsv from the census files and the catalog. */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { Catalog } from '../../app/core/catalog/types.ts';
import { loadNames, loadOverrides, lineageFor, matchCensus } from './merge.ts';
import type { CensusFile } from './types.ts';

const docs = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'docs');
const pct = (a: number, b: number) => (b === 0 ? '0%' : `${Math.round((a / b) * 100)}%`);
const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\s+/g, ' ');

/** Browsers that cannot be read from open source, and why. */
const NOT_COVERED: [string, string][] = [
  ['Internet Explorer 1–3, 6, 9–11, Edge Legacy', 'IE 4, 5, 7 and 8 are covered from menus read out of their own programs (Internet Archive downloads). IE 1–3 at the Archive are 16-bit or AOL builds the reader does not handle; IE 6 there is a web installer with nothing inside; the stand-alone IE collection is password-encrypted and was not opened. IE 9–11 not yet tried.'],
  ['Netscape 1.x, 4.5, 4.8, 6–9', 'Mosaic Netscape 0.91, Navigator 2.02 and 3.0 and Communicator 4.05 and 4.7 are covered from their own programs, plus three manuals and two screenshots. Netscape 6–9 are Mozilla-based (their menus are in Mozilla\'s code, covered by SeaMonkey).'],
  ['Opera 2–6, 9–11, 15+', 'Opera 8.01 and 12.14 are covered from their menu files. Opera 2–3 at the Archive are 16-bit programs; the 9.x and 10.x installers use an InstallShield format not unpacked here. Opera 15+ is Chromium-based. Otter Browser, an Opera 12 style clone, is also covered.'],
  ['Safari (menu bar), Camino, OmniWeb, iCab', 'Closed source. Safari\'s page context menu is covered from WebKit (2010 and current); its menu bar is not.'],
  ['Arc, Sidekick, SigmaOS, Zen, Floorp; Vivaldi before 3.4', 'Closed source or no menu file in a reachable repository. Vivaldi 3.4 and 6.9 are covered from the menu files inside their official Linux builds (Arch Linux package archive at the Internet Archive). Arc features appear in the roadmap from public descriptions, not from a source.'],
  ['Firefox 1.0–100 (history)', 'The gecko-dev mirror has no release tags; only the current tree was read. SeaMonkey 2.0 covers 2009.'],
  ['Konqueror 3, Galeon, Epiphany, Flock', 'Konqueror 4.0 and 4.14 are covered from kde-baseapps (menu file and handbook); KDE 3 tags were not found in the mirrors reachable here.'],
  ['K-Meleon, Pale Moon, Basilisk, Waterfox', 'Hosted outside GitHub.'],
  ['Mobile browsers (Opera Mini, Samsung Internet, UC, Dolphin, Kiwi)', 'Closed source.'],
];

export function writeCensusReports(files: readonly CensusFile[], catalog: Catalog, today: string): { problems: string[] } {
  const ids = new Set(catalog.commands.map((c) => c.id));
  const r = matchCensus(files, loadNames(), loadOverrides(), ids);
  const total = files.reduce((n, f) => n + f.items.length, 0);
  const perSource = (f: CensusFile) => ({
    linked: r.matches.filter((m) => m.source === f).length,
    reviewed: r.reviewed.filter((m) => m.source === f).length,
    open: r.unmatched.filter((m) => m.source === f).length,
  });

  const withCensus = catalog.commands.filter((c) => lineageFor(c.id, r.matches).length > 0);
  const recalledOnly = catalog.commands.filter((c) => lineageFor(c.id, r.matches).length === 0 && (c.lineage ?? []).length > 0);
  const none = catalog.commands.filter((c) => lineageFor(c.id, r.matches).length === 0 && !(c.lineage ?? []).length);
  const browsers = new Set(files.map((f) => f.browser));

  const out: string[] = [];
  out.push(
    '# Command census',
    '',
    `<!-- Generated by \`npm run census -- docs\` on ${today}. Do not edit by hand. -->`,
    '',
    'The census records which commands real browsers offered, read from their own source code at an exact commit. It is the evidence behind each command\'s "Seen in" history (Help > Menu Archaeology).',
    '',
    '## Summary',
    '',
    `- **${files.length} browser versions** from **${browsers.size} browsers**, **${total} items** read.`,
    `- **${r.matches.length} items (${pct(r.matches.length, total)})** are linked to a canonical command; **${r.reviewed.length}** were read and deliberately not linked; **${r.unmatched.length}** are not yet linked (work queue: [census-unlinked.tsv](census-unlinked.tsv)).`,
    `- **${catalog.commands.length} canonical commands**: ${withCensus.length} have lineage read from source, ${recalledOnly.length} have only lineage written from memory (marked *recalled*), ${none.length} have none yet.`,
    '',
    '## What a census entry proves, and what it does not',
    '',
    '- **Proves:** a command with that identifier (and, where the source has one, that label or description) existed in that file at that commit. `npm run census:verify` re-fetches every file and checks its hash and that each cited line still contains the recorded text.',
    '- **Does not prove:** that two items in different browsers behave the same. That is a judgement made when linking, recorded in `catalog/census/names/` and `catalog/census/overrides.yaml`, and checked against each source\'s own description where it has one (Lynx, w3m, ELinks, Vimium, qutebrowser). Wrong links were caught that way (for example the w3m command `UNDO`, which undoes a cursor movement); see the `why` fields in the overrides file.',
    '- **Manuals** (sources marked "manual (OCR)") are scanned books about a browser, held by the Internet Archive. Only fixed phrasings such as "From the File menu, choose Open Location" are read, so they give a sample of the menus, not a full listing; OCR can misspell; and a book may describe other programs too. Every manual item was read in context before linking, and look-alikes are listed below with the reason. They are shown in the app as "manual", distinct from source code.',
    '- **Menus read from programs** (where column \"program\'s own menus\"): installers downloaded from the Internet Archive were unpacked (InstallShield 3 archives by `tools/census/is3.ts`, cabinets by `cabextract`, Inno Setup by `innoextract`) and the Windows menu resources read by `tools/pe-dump.ts`; nothing was run. Opera 8 and 12 keep their menus in a text file, read by `tools/opera-dump.ts`. Each dump in `catalog/census/transcriptions/` records the download, how it was unpacked and the SHA-256 of every file read. Netscape\'s comments carry its own status-bar text; Internet Explorer does not keep that text by command id, so its dumps carry only shortcuts. Mail, news, Composer, address book and script-debugger menus were dumped too, but most of their items are left unlinked: they belong to programs this browser does not include.',
    '- **Screenshots** (sources marked "screenshot") are transcriptions of images on Wikimedia Commons, read by a model and kept in `catalog/census/transcriptions/` with the image address and hash. They show only what was visible: menu titles and toolbar buttons, not the contents of closed menus. Menu titles are recorded but never linked as commands.',
    '- **Re-creations and engines.** Wine\'s `ieframe.dll` is a re-implementation of Internet Explorer: it shows the menu Wine copied, not Internet Explorer itself. Safari\'s page context menu is defined in WebKit, which Apple publishes, so that part of Safari is read from Apple\'s own code; Safari\'s menu bar is not.',
    '- **Release years** are not read from the source. They are common knowledge, entered by hand in `catalog/census/sources.yaml`. Check before citing.',
    '- Menu items inside compile-time conditions (`#ifdef VMS`, `HAVE_DTM`) are included: they were commands on some builds. Rows compiled out by `#ifdef NOT_USED` are excluded.',
    '- Items such as Chromium\'s internal `IDC_*` ids are real command ids but not all are user-facing; the unlinked queue contains many of these.',
    '',
    '## Sources read',
    '',
    '| Source | Browser | Version | Year | Commit | Items | Linked | Reviewed, not linked | Not yet linked |',
    '|---|---|---|---|---|---|---|---|---|',
  );
  for (const f of files) {
    const p = perSource(f);
    const sha = f.source.commit.slice(0, 10);
    const where = f.source.host === 'machine'
      ? `menus read on a contributor's computer: ${cell(f.source.repo)}`
      : f.source.host === 'dump'
      ? `program's own menus: [archive.org/${cell(f.source.repo)}](https://archive.org/details/${f.source.repo})`
      : f.source.host === 'local'
      ? `screenshot: [Commons ${cell(f.source.repo)}](https://commons.wikimedia.org/wiki/File:${encodeURIComponent(f.source.repo)})`
      : f.source.host === 'archive.org'
      ? `manual (OCR): [archive.org/${f.source.repo}](https://archive.org/details/${f.source.repo})`
      : `[${f.source.repo}@${sha}](https://github.com/${f.source.repo}/tree/${f.source.commit})`;
    out.push(`| \`${f.id}\` | ${cell(f.browser)} | ${cell(f.browser_version)} | ${f.released} | ${where} | ${f.items.length} | ${p.linked} (${pct(p.linked, f.items.length)}) | ${p.reviewed} | ${p.open} |`);
  }
  out.push('', '## Not covered', '', 'These cannot be read from the build environment, so they have **no census lineage**. Anything the catalog says about them is from memory and marked *recalled*.', '', '| Browsers | Why |', '|---|---|');
  for (const [b, why] of NOT_COVERED) out.push(`| ${b} | ${why} |`);
  out.push('', '## Read and deliberately not linked', '');
  if (r.reviewed.length === 0) out.push('None.');
  else {
    out.push('| Source | Item | Why |', '|---|---|---|');
    for (const x of r.reviewed) out.push(`| \`${x.source.id}\` | \`${x.item.key}\` | ${cell(x.why)} |`);
  }
  const groups: Record<string, number> = {};
  for (const u of r.unmatched) {
    const k = u.item.key;
    const g = /^IDC_CONTENT_CONTEXT|^IDC_MEDIA_CONTEXT|^IDC_EXTENSIONS_CONTEXT/.test(k) ? 'Chromium page context menu entries'
      : /^IDC_BOOKMARK_BAR/.test(k) ? 'Chromium bookmark bar menu entries'
      : /^IDC_(DEV_TOOLS|MEDIA_ROUTER|SPELLCHECK|OMNIBOX|GLIC)/.test(k) ? 'Chromium developer, cast, spelling and assistant entries'
      : /^IDC_/.test(k) ? 'Other Chromium and Brave ids'
      : u.source.id === 'qutebrowser-current' && /^(move-to|rl-|debug-|config-|completion|command-|prompt-|selection-)/.test(k) ? 'qutebrowser caret, readline, config, debug and prompt commands'
      : u.source.id === 'mosaic-2.7' && /^mo_news/.test(k) ? 'Mosaic Usenet news reader'
      : u.source.id === 'elinks-current' && /^main:(move|macro|frame|toggle)/.test(k) ? 'ELinks cursor movement, macros, frames and toggles'
      : u.source.id.startsWith('w3m') && /^(MOVE|NEXT|PREV|CURSOR|LINE|MARK|SEARCH|TAB|GOTO|SELECT|MENU)/.test(k) ? 'w3m cursor, link, mark and buffer navigation'
      : 'Other';
    groups[g] = (groups[g] ?? 0) + 1;
  }
  out.push('', '## Work queue', '', `${r.unmatched.length} items are not yet linked. They fall into these groups:`, '', '| Group | Items |', '|---|---|');
  for (const [g, n] of Object.entries(groups).sort((a, b) => b[1] - a[1])) out.push(`| ${g} | ${n} |`);
  out.push(
    '',
    'To work through it: read an item in [census-unlinked.tsv](census-unlinked.tsv), find or create the canonical command, add its normalized name to a file in `catalog/census/names/` (or an entry in `overrides.yaml` for an ambiguous word), then run `npm run catalog`. The build fails if a name would belong to two commands.',
    '',
    '## Commands without census lineage',
    '',
    none.length === 0 ? 'None.' : none.map((c) => `\`${c.id}\``).join(', '),
    '',
  );
  writeFileSync(join(docs, 'CENSUS.md'), out.join('\n'));

  const tsv = ['source\tkey\tlabel_or_note\tmenu_or_group\tline'];
  for (const u of r.unmatched) {
    tsv.push([u.source.id, u.item.key, u.item.label ?? u.item.note ?? '', u.item.menu ?? u.item.group ?? '', u.item.line].map((v) => String(v).replace(/[\t\n]/g, ' ')).join('\t'));
  }
  writeFileSync(join(docs, 'census-unlinked.tsv'), `${tsv.join('\n')}\n`);
  return { problems: r.problems };
}
